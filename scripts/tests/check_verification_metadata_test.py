#!/usr/bin/env python3
"""Self-test for scripts/check_verification_metadata.py (MR-1794).

On a pull request with no dependency change the guard has nothing to find, so
a guard that could never fail would look the same. These fixtures prove each
failure it exists to catch, and that a plain version bump passes.
Run: python3 scripts/tests/check_verification_metadata_test.py
"""
from __future__ import annotations

import contextlib
import importlib.util
import io
import os
import sys
import tempfile
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
_spec = importlib.util.spec_from_file_location(
    "check_verification_metadata", os.path.join(ROOT, "scripts", "check_verification_metadata.py"))
guard = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(guard)

A = "a" * 64
B = "b" * 64
C = "c" * 64

CONFIG = """
   <configuration>
      <verify-metadata>true</verify-metadata>
      <verify-signatures>false</verify-signatures>
      <trusted-artifacts>
         <trust file=".*-javadoc[.]jar" regex="true"/>
         <trust file=".*-sources[.]jar" regex="true"/>
      </trusted-artifacts>
   </configuration>"""


def doc(components: str, config: str = CONFIG) -> str:
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<verification-metadata xmlns="https://schema.gradle.org/dependency-verification">'
            f"{config}\n   <components>{components}\n   </components>\n</verification-metadata>\n")


def component(group: str, name: str, version: str, sha: str, extra: str = "") -> str:
    return (f'\n      <component group="{group}" name="{name}" version="{version}">'
            f'\n         <artifact name="{name}-{version}.jar">'
            f'\n            <sha256 value="{sha}" origin="Generated by Gradle"{extra}'
            "\n         </artifact>\n      </component>")


OKHTTP_1 = component("com.squareup.okhttp3", "okhttp", "5.5.1", A, "/>")
OKHTTP_2 = component("com.squareup.okhttp3", "okhttp", "5.6.0", B, "/>")
SENTRY = component("io.sentry", "sentry", "8.63.0", C, "/>")


class GuardTest(unittest.TestCase):
    def run_guard(self, base: str | None, candidate: str) -> tuple[int, str]:
        with tempfile.TemporaryDirectory() as tmp:
            base_path = os.path.join(tmp, "base.xml")
            file_path = os.path.join(tmp, "file.xml")
            if base is not None:
                with open(base_path, "w", encoding="utf-8") as f:
                    f.write(base)
            with open(file_path, "w", encoding="utf-8") as f:
                f.write(candidate)
            out = io.StringIO()
            with contextlib.redirect_stdout(out):
                rc = guard.main(["--base", base_path, "--file", file_path, "--label", "candidate"])
            return rc, out.getvalue()

    def test_identical_passes(self):
        rc, out = self.run_guard(doc(OKHTTP_1 + SENTRY), doc(OKHTTP_1 + SENTRY))
        self.assertEqual(rc, 0, out)
        self.assertNotIn("::error::", out)

    def test_version_bump_passes_and_is_listed(self):
        rc, out = self.run_guard(doc(OKHTTP_1 + SENTRY), doc(OKHTTP_2 + SENTRY))
        self.assertEqual(rc, 0, out)
        self.assertIn("+ com.squareup.okhttp3:okhttp:5.6.0", out)
        self.assertIn("- com.squareup.okhttp3:okhttp:5.5.1", out)

    def test_changed_checksum_fails(self):
        changed = component("com.squareup.okhttp3", "okhttp", "5.5.1", B, "/>")
        rc, out = self.run_guard(doc(OKHTTP_1 + SENTRY), doc(changed + SENTRY))
        self.assertEqual(rc, 1, out)
        self.assertIn("::error::CHANGED CHECKSUM com.squareup.okhttp3:okhttp:5.5.1 okhttp-5.5.1.jar", out)

    def test_added_also_trust_fails(self):
        widened = component("com.squareup.okhttp3", "okhttp", "5.5.1", A,
                            f'>\n               <also-trust value="{B}"/>\n            </sha256>')
        rc, out = self.run_guard(doc(OKHTTP_1), doc(widened))
        self.assertEqual(rc, 1, out)
        self.assertIn("::error::CHANGED CHECKSUM com.squareup.okhttp3:okhttp:5.5.1", out)

    def test_configuration_change_fails(self):
        loosened = CONFIG.replace("<verify-metadata>true", "<verify-metadata>false")
        rc, out = self.run_guard(doc(OKHTTP_1), doc(OKHTTP_1, loosened))
        self.assertEqual(rc, 1, out)
        self.assertIn("::error::CONFIGURATION CHANGED", out)

    def test_added_trust_rule_fails(self):
        widened = CONFIG.replace("</trusted-artifacts>",
                                 '   <trust group="com.squareup.okhttp3"/>\n      </trusted-artifacts>')
        rc, out = self.run_guard(doc(OKHTTP_1), doc(OKHTTP_1, widened))
        self.assertEqual(rc, 1, out)
        self.assertIn("::error::CONFIGURATION CHANGED", out)

    def test_whitespace_only_configuration_change_passes(self):
        reflowed = CONFIG.replace("\n      <verify-signatures>", "<verify-signatures>")
        rc, out = self.run_guard(doc(OKHTTP_1), doc(OKHTTP_1, reflowed))
        self.assertEqual(rc, 0, out)

    def test_missing_base_passes(self):
        rc, out = self.run_guard(None, doc(OKHTTP_1))
        self.assertEqual(rc, 0, out)
        self.assertIn("nothing to compare against", out)

    def test_every_failure_is_reported_not_just_the_first(self):
        loosened = CONFIG.replace("<verify-signatures>false", "<verify-signatures>true")
        changed_ok = component("com.squareup.okhttp3", "okhttp", "5.5.1", B, "/>")
        changed_se = component("io.sentry", "sentry", "8.63.0", A, "/>")
        rc, out = self.run_guard(doc(OKHTTP_1 + SENTRY), doc(changed_ok + changed_se, loosened))
        self.assertEqual(rc, 1, out)
        self.assertEqual(out.count("::error::CHANGED CHECKSUM"), 2, out)
        self.assertEqual(out.count("::error::CONFIGURATION CHANGED"), 1, out)


if __name__ == "__main__":
    sys.exit(0 if unittest.main(exit=False, verbosity=1).result.wasSuccessful() else 1)
