/**
 * Maps the device onto a [GlobeQuality]. A context with no ActivityManager is
 * not a real device (a stripped test or preview context), so it gets the cheap
 * path rather than the expensive one.
 */
private fun globeQualityFor(context: Context): GlobeQuality {
    val am = context.getSystemService(Context.ACTIVITY_SERVICE) as? ActivityManager
        ?: return GlobeQuality.LITE
    return GlobeQuality.forDevice(am.isLowRamDevice, am.memoryClass)
}

/**
 * Applies the perf HUD's tier pin, if the HUD is compiled in at all.
 *
 * The `GlobePerf.ENABLED` guard is a `static final boolean` in a stock release
 * build, so this returns [auto] without ever subscribing the composition to the
 * debug state.
 */
@Composable
private fun debugQualityOverride(auto: GlobeQuality): GlobeQuality {
    if (!GlobePerf.ENABLED) return auto
    return when (GlobePerfControls.forcedLite.value) {
        null -> auto
        true -> GlobeQuality.LITE
        false -> GlobeQuality.FULL
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// Pre-computation (runs once, off the hot path)
// ─────────────────────────────────────────────────────────────────────────────

/** Floats per star in the packed buffer: x, y, baseAlpha, sinPhase, cosPhase, radius. */
private const val STAR_STRIDE = 6

/** Normalized 0..1 phase of a cycle of [periodMs] at time [clockMs]. */
private fun cyclePhase(clockMs: Long, periodMs: Long): Float =
    (clockMs % periodMs).toFloat() / periodMs.toFloat()

/**
 * Star field, packed.
 *
 * The RNG is consumed in exactly the original order (x, y, brightness per star)
 * so positions and brightnesses are bit-identical to previous releases, and a
 * smaller [count] is a strict prefix of the full field rather than a different
 * sky. The twinkle phase is folded into `sin`/`cos` here so the per-frame
 * `sin(twinkle*2PI + phase)` becomes one angle-addition per star: two
 * transcendental calls per frame for the whole field instead of one per star.
 */
private fun precomputeStars(count: Int): FloatArray {
    val rng = Random(0xB16D0L)
    val arr = FloatArray(count * STAR_STRIDE)
    var i = 0
    while (i < arr.size) {
        val x = rng.nextFloat()
        val y = rng.nextFloat()
        val b = rng.nextFloat()
        val phase = b * 13.7f
        arr[i] = x
        arr[i + 1] = y
        arr[i + 2] = b * 0.65f + 0.18f
        arr[i + 3] = sin(phase)
        arr[i + 4] = cos(phase)
        arr[i + 5] = if (b > 0.85f) 1.5f else 0.9f
        i += STAR_STRIDE
    }
    return arr
}

/** Packs `[sinPhi, cosPhi*cos(lon), cosPhi*sin(lon)]` per server, matching [LandSamples]. */
private fun packServerGeometry(points: List<Triple<String, Double, Double>>): FloatArray {
    val arr = FloatArray(points.size * 3)
    var i = 0
    for (p in points) {
        val phi = p.second * PI / 180.0
        val lon = p.third * PI / 180.0
        val cosPhi = cos(phi)
        arr[i] = sin(phi).toFloat()
        arr[i + 1] = (cosPhi * cos(lon)).toFloat()
        arr[i + 2] = (cosPhi * sin(lon)).toFloat()
        i += 3
    }
    return arr
}

private fun lerpAngleDeg(a: Float, b: Float, t: Float): Float {
    var d = (b - a) % 360f
    if (d > 180f) d -= 360f
    if (d < -180f) d += 360f
    return a + d * t
}

