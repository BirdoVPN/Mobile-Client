/**
 * Mullvad-style 3D rotating orthographic globe.
 *
 * This is the first thing a new install sees, so its cost lands exactly on the
 * install -> first-open step, on the oldest hardware in the fleet.
 *
 * Performance-critical decisions:
 *
 *  - **No trigonometry in the continent loop** (v1.4.21). Cell longitudes are
 *    pre-folded into `cosPhi*cos(lon)` / `cosPhi*sin(lon)` products so the
 *    camera rotation becomes two multiply-adds, and the back-face cull runs
 *    BEFORE the work only visible cells need. See [GlobeGeometry]; the maths
 *    and the emitted-quad counts are pinned by `GlobeGeometryTest`.
 *  - **Brushes are cached across frames** ([GlobeBrushes]). `Brush.radialGradient`
 *    caches its native shader INSIDE the brush instance, so building a fresh
 *    instance per frame defeats that cache entirely. All six gradients are now
 *    keyed on disc geometry (and rebuilt via `remember` when the theme changes),
 *    so a steady-state frame constructs ZERO shaders. The two sun-tracking
 *    gradients keep a fixed centre and are moved with a canvas `translate`,
 *    which is a matrix push rather than a shader rebuild.
 *  - Land cell positions live in one flat `FloatArray`, walked by a single
 *    while loop. Three retained `Path` objects accumulate the squares per
 *    brightness bucket and are reused across frames via `Path.reset()`.
 *  - The great-circle connection arc is generated by slerp on the unit sphere
 *    and projected segment-by-segment, so it follows the curvature of the
 *    planet and naturally clips when it dips behind the limb.
 *  - All heavy rendering lives in a top-level `DrawScope` extension, dodging
 *    the Compose compiler stack-overflow that bit us on v1.3.10 CI.
 *
 * Allocation honesty. The previous version of this comment claimed the renderer
 * made "no Rect, Triple, Pair, list/iterator allocations" — true of the land
 * loop and false of everything below it, which is how ~12 allocations and 6
 * native shader constructions per frame survived two optimisation passes. What
 * is true now: the land, star, server-dot and gradient paths allocate nothing in
 * a steady-state frame. The arc path and Compose's own draw scope still do.
 * Do not restore a blanket "no allocations" claim without re-checking it.
 */
@Composable
fun WorldGlobe(
    servers: List<VpnServer>,
    selectedServerId: String?,
    isConnected: Boolean,
    modifier: Modifier = Modifier,
    autoRotate: Boolean = true,
    userLat: Double = 51.51,
    userLon: Double = -0.13,
) {
    val palette = BirdoColors.current
    val context = LocalContext.current

    // Cost profile for THIS device. Read once — neither the RAM tier nor the
    // heap class changes while the app is alive.
    val autoQuality = remember(context) { globeQualityFor(context) }
    // Debug builds (and a release built with -PperfOverlay=true) can pin the
    // tier from the perf HUD, so FULL and LITE can be compared on ONE device
    // instead of inferred across two. Constant-folds away otherwise.
    val quality = debugQualityOverride(autoQuality)

    // Label every frame produced while this globe is composed with its tier, so
    // JankStats can partition its histogram into globe-on and globe-off. This
    // runs on composition and on tier change — never per frame.
    val perfView = LocalView.current
    if (GlobePerf.ENABLED) {
        DisposableEffect(perfView, quality) {
            GlobePerfState.set(
                perfView,
                if (quality.lite) GlobePerf.STATE_LITE else GlobePerf.STATE_FULL,
            )
            onDispose { GlobePerfState.set(perfView, GlobePerf.STATE_OFF) }
        }
    }

    // Power: the globe is a full-screen Canvas driven by an animation clock.
    // Compose keeps invalidating it at the display refresh rate (90/120 Hz on
    // modern phones) for as long as it is composed — even while the Activity is
    // STOPPED, because an animation is not lifecycle-aware. Gate the whole thing
    // on the lifecycle: when the app isn't at least STARTED (screen off, recents,
    // another app on top) we stop driving the animation entirely and draw one
    // static frame. Leaving composition (navigating away, or HomeScreen swapping
    // the globe out for a flat backdrop while the server sheet is open) cancels
    // the driver outright, because it lives in a LaunchedEffect.
    //
    // The idle rotation is also intentionally slow (a 90s revolution), so
    // redrawing 21k land cells 120x/second buys nothing visible. We snap the
    // animation clock to ~30 fps (20 on the lite path), which is smooth for this
    // content and cuts globe frame work by 2-4x on a high-refresh display.
    val lifecycleOwner = LocalLifecycleOwner.current
    var started by remember { mutableStateOf(true) }
    // Accessibility / battery saver: "Remove animations" sets the system
    // animator duration scale to 0. Compose's own tween animations already
    // honour it through MotionDurationScale, but our hand-rolled clock does not
    // — so a user who has asked for no animation would still get a spinning
    // planet, and would still pay for it. Re-read on every ON_START because the
    // setting can change while we are away.
    var animatorsEnabled by remember { mutableStateOf(true) }
    DisposableEffect(lifecycleOwner) {
        animatorsEnabled = ValueAnimator.areAnimatorsEnabled()
        val observer = LifecycleEventObserver { _, event ->
            when (event) {
                Lifecycle.Event.ON_START -> {
                    started = true
                    animatorsEnabled = ValueAnimator.areAnimatorsEnabled()
                }
                Lifecycle.Event.ON_STOP -> started = false
                else -> Unit
            }
        }
        lifecycleOwner.lifecycle.addObserver(observer)
        onDispose { lifecycleOwner.lifecycle.removeObserver(observer) }
    }
    val animating = started && animatorsEnabled

    // ONE animation clock. Every cyclic value below is a pure function of
    // elapsed time, so a single monotonic millisecond counter reproduces them
    // exactly — but invalidates the Canvas at our chosen cadence rather than the
    // display's, and stops dead when the app is not visible. Elapsed time
    // accumulates across pauses so the sun and the spin resume where they left
    // off instead of snapping back.
    var clockMs by remember { mutableLongStateOf(0L) }
    val frameIntervalMs = quality.frameIntervalMs
    LaunchedEffect(animating, frameIntervalMs) {
        if (!animating) return@LaunchedEffect
        var lastFrame = withFrameMillis { it }
        // `elapsed` free-runs on every vsync; `clockMs` (the snapshot state the
        // Canvas reads) is only PUBLISHED once per frameIntervalMs. Keeping
        // these separate matters: accumulating into the published value instead
        // would discard every sub-threshold frame's delta, and since one frame
        // is 8-16ms and the threshold is 33ms, the clock would never advance at
        // all — a frozen globe on every normal display.
        var elapsed = clockMs
        var lastEmit = clockMs
        while (true) {
            withFrameMillis { frame ->
                // Guard against a huge delta if the choreographer stalls.
                val delta = (frame - lastFrame).coerceIn(0L, 250L)
                lastFrame = frame
                elapsed += delta
                if (elapsed - lastEmit >= frameIntervalMs) {
                    lastEmit = elapsed
                    clockMs = elapsed
                }
            }
        }
    }

    val pulse = cyclePhase(clockMs, 1800L)
    val arcShimmer = cyclePhase(clockMs, 2400L)
    val twinkle = cyclePhase(clockMs, 3600L)
    val idleSpin = cyclePhase(clockMs, 90_000L) * 360f
    // Day/night terminator: the sun's longitude sweeps a full revolution
    // every 2 minutes. Independent of the camera so you can see the shadow
    // crawl across continents while the globe is still / focused.
    val sunSpin = cyclePhase(clockMs, 120_000L) * 360f

    // One-shot precomputation. ~21 k land cells (~5 k on the lite path) stored
    // as packed floats.
    val landSamples = remember(quality) {
        GlobeGeometry.packLandSamples(
            rows = WorldLandmask.rowCount(),
            cols = WorldLandmask.colCount(),
            strideRow = quality.landStride,
            strideCol = quality.landStride,
            isLand = { r, c -> WorldLandmask.isLandCell(r, c) },
        )
    }
    val stars = remember(quality) { precomputeStars(quality.starCount) }
    val landSink = remember { PathQuadSink(Path(), Path(), Path()) }
    val arcPath = remember { Path() }

    val serverPoints = remember(servers) {
        servers.mapNotNull { s ->
            CountryCoords.forCountry(s.countryCode)?.let { ll ->
                Triple(s.id, ll.first, ll.second)
            }
        }
    }
    // The dot pass used to re-derive sin/cos of every server's lat/lon on every
    // frame and iterate a List<Triple<String, Double, Double>> — an iterator
    // allocation per frame, boxed Doubles per read. Same trick as the land
    // buffer: fold the fixed part into packed floats once.
    val serverIds = remember(serverPoints) {
        Array(serverPoints.size) { serverPoints[it].first }
    }
    val serverGeom = remember(serverPoints) { packServerGeometry(serverPoints) }

    val selectedCoord = remember(selectedServerId, serverPoints) {
        serverPoints.firstOrNull { it.first == selectedServerId }
            ?.let { it.second to it.third }
    }

    // Focal target: midpoint of (user, server) when something is selected so
    // the connection arc sweeps across the visible front face.
    val hasFocus = selectedCoord != null
    var focusLatTarget = 0f
    var focusLonTarget = 0f
    if (hasFocus) {
        val sLat = selectedCoord!!.first.toFloat()
        val sLon = selectedCoord.second.toFloat()
        val uLat = userLat.toFloat()
        val uLon = userLon.toFloat()
        val rawDLon = sLon - uLon
        val shiftedSLon = when {
            rawDLon > 180f -> sLon - 360f
            rawDLon < -180f -> sLon + 360f
            else -> sLon
        }
        focusLatTarget = (uLat + sLat) / 2f
        focusLonTarget = (uLon + shiftedSLon) / 2f
    }

    val focus by animateFloatAsState(
        targetValue = if (hasFocus) 1f else 0f,
        animationSpec = tween(1400, easing = FastOutSlowInEasing),
        label = "focus",
    )
    val zoom by animateFloatAsState(
        targetValue = when {
            isConnected -> 1.20f
            hasFocus -> 1.06f
            else -> 1f
        },
        animationSpec = tween(1200, easing = FastOutSlowInEasing),
        label = "zoom",
    )
    val arcProgress by animateFloatAsState(
        targetValue = if (isConnected && hasFocus) 1f else 0f,
        animationSpec = tween(900, delayMillis = if (isConnected) 400 else 0),
        label = "arcProgress",
    )

    val idleLon = if (autoRotate) (idleSpin + userLon.toFloat() - 25f) else userLon.toFloat()
    val effectiveLat = focusLatTarget * focus
    val effectiveLon = lerpAngleDeg(idleLon, focusLonTarget, focus)

    // NOTE: the "light" theme here is Birdo's DIM-light theme (a slate near-dark,
    // #1B1C24) — not a true white theme. These used to be a daylight globe on a
    // near-white #EEF1F8 sky, which painted a glaring white panel into the middle
    // of an otherwise dim UI: exactly the "too bright" complaint the dim theme
    // exists to answer. Both themes now render a NIGHT earth; the dim theme just
    // sits a few steps lighter than the OLED one, and the sky is taken straight
    // from the palette so it can never drift from the app background again.
    val isLight = palette.isLight
    val space = if (isLight) palette.background else Color(0xFF030714)
    val starColor = if (isLight) Color(0xFF5A6580) else Color(0xFFB6C5E2)
    val oceanCore = if (isLight) Color(0xFF26334A) else Color(0xFF1A3050)
    val oceanRim = if (isLight) Color(0xFF141B29) else Color(0xFF071426)
    val landDimC = if (isLight) Color(0xFF33445F) else Color(0xFF1F4364)
    val landMidC = if (isLight) Color(0xFF46628A) else Color(0xFF356D9F)
    val landLitC = if (isLight) Color(0xFF5E86B5) else Color(0xFF59A8E0)
    val atmosphere = if (isLight) Color(0xFF4B7BB0) else Color(0xFF4983C7)
    val rim = if (isLight) Color(0xFF6C9AC9) else Color(0xFF7BB2E6)
    val accent = palette.accent
    val connected = if (isLight) Color(0xFF059669) else Color(0xFF34D399)

    // Shader cache. Keyed on every colour that can end up baked into a gradient,
    // so a theme flip throws the whole cache away rather than leaving a stale
    // shader on screen. Within a theme the slots are keyed on disc geometry, so
    // they miss only while the zoom tween is running.
    val brushes = remember(isLight, atmosphere, oceanCore, oceanRim) { GlobeBrushes() }

    // Sun position: slow east-to-west drift in longitude with a small
    // seasonal-ish latitude tilt so the terminator isn't a perfect vertical.
    val sunLonDeg = 180f - sunSpin
    val sunLatDeg = 12f

    Canvas(modifier = modifier.fillMaxSize()) {
        renderGlobe(
            stars = stars,
            landSamples = landSamples,
            landSink = landSink,
            arcPath = arcPath,
            brushes = brushes,
            quality = quality,
            space = space,
            starColor = starColor,
            oceanCore = oceanCore,
            oceanRim = oceanRim,
            landDim = landDimC,
            landMid = landMidC,
            landLit = landLitC,
            atmosphere = atmosphere,
            rim = rim,
            accent = accent,
            connectedColor = connected,
            isLight = isLight,
            isConnected = isConnected,
            focusLatDeg = effectiveLat,
            focusLonDeg = effectiveLon,
            zoom = zoom,
            twinkle = twinkle,
            pulse = pulse,
            arcShimmer = arcShimmer,
            arcProgress = arcProgress,
            serverIds = serverIds,
            serverGeom = serverGeom,
            selectedServerId = selectedServerId,
            selectedCoord = selectedCoord,
            userLat = userLat,
            userLon = userLon,
            sunLatDeg = sunLatDeg,
            sunLonDeg = sunLonDeg,
        )
    }
}

