/** Accumulates the continent pass into three retained paths, one per brightness bucket. */
private class PathQuadSink(
    @JvmField val dim: Path,
    @JvmField val mid: Path,
    @JvmField val lit: Path,
) : LandQuadSink {

    fun reset() {
        dim.reset()
        mid.reset()
        lit.reset()
    }

    override fun quad(bucket: Int, px: Float, py: Float, half: Float) {
        val target = when (bucket) {
            GlobeGeometry.BUCKET_LIT -> lit
            GlobeGeometry.BUCKET_MID -> mid
            else -> dim
        }
        // No Rect allocation — primitive moves only.
        target.moveTo(px - half, py - half)
        target.lineTo(px + half, py - half)
        target.lineTo(px + half, py + half)
        target.lineTo(px - half, py + half)
        target.close()
    }
}

/**
 * One cached [Brush] plus the geometry it was built for.
 *
 * [obtain] is `inline` on purpose: a non-inline builder lambda would be
 * allocated on every call, hit or miss, which is exactly the per-frame garbage
 * the cache exists to remove.
 */
private class BrushSlot {
    @JvmField var k0: Float = Float.NaN
    @JvmField var k1: Float = Float.NaN
    @JvmField var k2: Float = Float.NaN
    @JvmField var brush: Brush? = null
}

private inline fun BrushSlot.obtain(a: Float, b: Float, c: Float, build: () -> Brush): Brush {
    val cached = brush
    if (cached != null && k0 == a && k1 == b && k2 == c) return cached
    val fresh = build()
    k0 = a
    k1 = b
    k2 = c
    brush = fresh
    return fresh
}

/** The six radial gradients a globe frame paints. */
private class GlobeBrushes {
    @JvmField val atmosphere = BrushSlot()
    @JvmField val ocean = BrushSlot()
    @JvmField val limb = BrushSlot()
    @JvmField val specular = BrushSlot()
    @JvmField val night = BrushSlot()
    @JvmField val sun = BrushSlot()
}

private val NIGHT_TINT = Color(0xFF02060F)
private val SUN_TINT = Color(0xFFFFE6B0)

// ─────────────────────────────────────────────────────────────────────────────
// Rendering (single hot path, all state passed in by value/reference)
// ─────────────────────────────────────────────────────────────────────────────

@Suppress("LongParameterList", "LongMethod", "ComplexCondition")
private fun DrawScope.renderGlobe(
    stars: FloatArray,
    landSamples: LandSamples,
    landSink: PathQuadSink,
    arcPath: Path,
    brushes: GlobeBrushes,
    quality: GlobeQuality,
    space: Color,
    starColor: Color,
    oceanCore: Color,
    oceanRim: Color,
    landDim: Color,
    landMid: Color,
    landLit: Color,
    atmosphere: Color,
    rim: Color,
    accent: Color,
    connectedColor: Color,
    isLight: Boolean,
    isConnected: Boolean,
    focusLatDeg: Float,
    focusLonDeg: Float,
    zoom: Float,
    twinkle: Float,
    pulse: Float,
    arcShimmer: Float,
    arcProgress: Float,
    serverIds: Array<String>,
    serverGeom: FloatArray,
    selectedServerId: String?,
    selectedCoord: Pair<Double, Double>?,
    userLat: Double,
    userLon: Double,
    sunLatDeg: Float,
    sunLonDeg: Float,
) {
    val w = size.width
    val h = size.height
    if (w <= 0f || h <= 0f) return

    drawRect(color = space, size = size)

    val cx = w * 0.5f
    val cy = h * 0.5f
    val baseR = min(w, h) * 0.46f
    val radius = baseR * zoom
    val atmR = radius * 1.22f
    val atmR2 = atmR * atmR

    // Star field — occluded by the globe disc (with atmosphere padding).
    run {
        // Angle addition: sin(A + phase) == sinA*cosPhase + cosA*sinPhase. Two
        // transcendental calls for the whole field instead of one per star.
        val angle = twinkle * (2.0 * PI).toFloat()
        val sinA = if (quality.twinkle) sin(angle) else 0f
        val cosA = if (quality.twinkle) cos(angle) else 0f
        var s = 0
        while (s < stars.size) {
            val sx = stars[s] * w
            val sy = stars[s + 1] * h
            val baseAlpha = stars[s + 2]
            val sinPhase = stars[s + 3]
            val cosPhase = stars[s + 4]
            val starR = stars[s + 5]
            s += STAR_STRIDE
            val dx = sx - cx
            val dy = sy - cy
            if (dx * dx + dy * dy < atmR2) continue
            val tw = if (quality.twinkle) {
                0.55f + 0.45f * (sinA * cosPhase + cosA * sinPhase)
            } else {
                1f
            }
            drawCircle(
                color = starColor.copy(alpha = baseAlpha * tw),
                radius = starR,
                center = Offset(sx, sy),
            )
        }
    }

    // Outer atmosphere — Fresnel-ish ring that peaks just outside the limb.
    drawCircle(
        brush = brushes.atmosphere.obtain(cx, cy, atmR) {
            Brush.radialGradient(
                colorStops = arrayOf(
                    0.78f to atmosphere.copy(alpha = 0f),
                    0.92f to atmosphere.copy(alpha = if (isLight) 0.22f else 0.36f),
                    1.0f to atmosphere.copy(alpha = 0f),
                ),
                center = Offset(cx, cy),
                radius = atmR,
            )
        },
        radius = atmR,
        center = Offset(cx, cy),
    )

    // Ocean disc with a directional radial gradient (lighter upper-left).
    drawCircle(
        brush = brushes.ocean.obtain(cx, cy, radius) {
            Brush.radialGradient(
                colors = listOf(oceanCore, oceanRim),
                center = Offset(cx - radius * 0.22f, cy - radius * 0.28f),
                radius = radius * 1.05f,
            )
        },
        radius = radius,
        center = Offset(cx, cy),
    )

    // Camera trig — five transcendental calls per FRAME for the whole renderer,
    // plus two for the star twinkle and two for the sun.
    val latRad = focusLatDeg * (PI.toFloat() / 180f)
    val lonRad = focusLonDeg * (PI.toFloat() / 180f)
    val cosLat = cos(latRad)
    val sinLat = sin(latRad)
    val cosLon = cos(lonRad)
    val sinLon = sin(lonRad)

    // Project a (lat, lon) sample. Returns [Offset.Unspecified] if the sample is
    // on the back hemisphere; callers must check. A nullable Offset would BOX —
    // Offset is a value class over a Long — so the sentinel is not a style
    // choice, it is the difference between allocating here and not.
    // (Local function to keep call sites readable; JIT will inline it.)
    fun project(latDeg: Double, lonDeg: Double): Offset {
        val phi = (latDeg * PI / 180.0).toFloat()
        val lam = (lonDeg * PI / 180.0).toFloat() - lonRad
        val cP = cos(phi)
        val sP = sin(phi)
        val sx = cP * sin(lam)
        val sy = sP
        val sz = cP * cos(lam)
        val ty = sy * cosLat - sz * sinLat
        val tz = sy * sinLat + sz * cosLat
        if (tz < 0f) return Offset.Unspecified
        return Offset(cx + sx * radius, cy - ty * radius)
    }

    // ── Continents: project pre-computed samples, cull the back hemisphere,
    // classify the survivors by lighting, accumulate three retained Paths.
    landSink.reset()
    GlobeGeometry.projectLandQuads(
        samples = landSamples,
        cx = cx,
        cy = cy,
        radius = radius,
        cosLat = cosLat,
        sinLat = sinLat,
        cosLon = cosLon,
        sinLon = sinLon,
        cellPx = radius * landSamples.cellSizeRad,
        sink = landSink,
    )
    drawPath(landSink.dim, color = landDim)
    drawPath(landSink.mid, color = landMid)
    drawPath(landSink.lit, color = landLit)

    // Inner limb darkening — clip-free vignette ring near the disc edge.
    drawCircle(
        brush = brushes.limb.obtain(cx, cy, radius) {
            Brush.radialGradient(
                colorStops = arrayOf(
                    0f to Color.Transparent,
                    0.65f to Color.Transparent,
                    1.0f to Color.Black.copy(alpha = if (isLight) 0.10f else 0.30f),
                ),
                center = Offset(cx, cy),
                radius = radius,
            )
        },
        radius = radius,
        center = Offset(cx, cy),
    )

    // Cool-blue rim stroke at the limb.
    drawCircle(
        color = rim.copy(alpha = if (isLight) 0.32f else 0.50f),
        radius = radius - 0.5f,
        center = Offset(cx, cy),
        style = Stroke(width = 1.2f),
    )

    // Specular highlight (upper-left).
    drawCircle(
        brush = brushes.specular.obtain(cx, cy, radius) {
            Brush.radialGradient(
                colors = listOf(
                    Color.White.copy(alpha = if (isLight) 0.18f else 0.10f),
                    Color.Transparent,
                ),
                center = Offset(cx - radius * 0.45f, cy - radius * 0.55f),
                radius = radius * 0.55f,
            )
        },
        radius = radius * 0.55f,
        center = Offset(cx - radius * 0.45f, cy - radius * 0.55f),
    )

    // ── Day / night terminator ────────────────────────────────────────────
    // Project the sun direction into camera space; the dark side is the
    // hemisphere opposite the sun. We draw a soft dark radial overlay
    // centred on the *anti-sun* point on the disc, plus a faint warm
    // highlight at the sub-solar point. Both stay inside the disc by being
    // sized to the radius.
    //
    // Both gradients MOVE every frame, which is the case that used to force a
    // fresh Brush (and therefore a fresh native shader) 30x/second. So the brush
    // is built once with its centre on the disc centre and the canvas is
    // translated instead: a matrix push costs nothing next to a shader rebuild,
    // and the pixels are the same — the circle is drawn at the inverse offset so
    // it lands back on the disc.
    run {
        val sPhi = sunLatDeg * (PI.toFloat() / 180f)
        val sLam = sunLonDeg * (PI.toFloat() / 180f) - lonRad
        val sCp = cos(sPhi)
        val ux = sCp * sin(sLam)
        val uy = sin(sPhi)
        val uz = sCp * cos(sLam)
        val sxCam = ux
        val syCam = uy * cosLat - uz * sinLat
        val szCam = uy * sinLat + uz * cosLat
        val sunPx = cx + sxCam * radius
        val sunPy = cy - syCam * radius
        val antiPx = cx - sxCam * radius
        val antiPy = cy + syCam * radius
        val nightAlpha = if (isLight) 0.22f else 0.55f
        val dayAlpha = if (isLight) 0.10f else 0.18f
        // Night veil — dark blob centred on the anti-solar point, fading out
        // before reaching the sub-solar side. Sized 1.6× radius so the edge
        // falls past the day/night boundary without a visible cutoff.
        val nightBrush = brushes.night.obtain(cx, cy, radius) {
            Brush.radialGradient(
                colorStops = arrayOf(
                    0.0f to NIGHT_TINT.copy(alpha = nightAlpha),
                    0.55f to NIGHT_TINT.copy(alpha = nightAlpha * 0.55f),
                    1.0f to Color.Transparent,
                ),
                center = Offset(cx, cy),
                radius = radius * 1.6f,
            )
        }
        val ndx = antiPx - cx
        val ndy = antiPy - cy
        translate(ndx, ndy) {
            drawCircle(
                brush = nightBrush,
                radius = radius,
                center = Offset(cx - ndx, cy - ndy),
            )
        }
        // Subtle warm sunlit hotspot — only meaningful when the sun is on
        // the visible hemisphere (szCam > 0). The szCam fade is applied as a
        // paint alpha rather than baked into the stops: for a gradient that
        // ends at Color.Transparent, scaling the first stop's alpha and scaling
        // the paint alpha produce the identical ramp, and only one of them
        // needs a new shader.
        if (quality.sunHotspot && szCam > 0f) {
            val sunBrush = brushes.sun.obtain(cx, cy, radius) {
                Brush.radialGradient(
                    colors = listOf(
                        SUN_TINT.copy(alpha = dayAlpha),
                        Color.Transparent,
                    ),
                    center = Offset(cx, cy),
                    radius = radius * 0.7f,
                )
            }
            val sdx = sunPx - cx
            val sdy = sunPy - cy
            translate(sdx, sdy) {
                drawCircle(
                    brush = sunBrush,
                    radius = radius,
                    center = Offset(cx - sdx, cy - sdy),
                    alpha = szCam,
                )
            }
        }
        // Sharper terminator line itself: thin curve where szCam ≈ 0. We
        // approximate by drawing a slim dark stroke along an ellipse passing
        // through the limb perpendicular to the sun vector. Cheap & looks
        // real enough.
        // (skipped — the gradient already sells the curvature.)
    }

    // ── Server dots — ALL visible by default so the user sees every choice.
    // Skip the selected one; it gets a bigger pin in the connection block.
    var k = 0
    while (k < serverIds.size) {
        val base = k * 3
        val id = serverIds[k]
        k++
        if (id == selectedServerId) continue
        // Same packed representation and same cull-before-work order as the
        // land pass, so no trigonometry here either.
        val sinPhi = serverGeom[base]
        val a = serverGeom[base + 1]
        val b = serverGeom[base + 2]
        val sz = a * cosLon + b * sinLon
        val tz = sinPhi * sinLat + sz * cosLat
        if (tz <= GlobeGeometry.FRONT_FACE_EPS) continue
        val sx = b * cosLon - a * sinLon
        val ty = sinPhi * cosLat - sz * sinLat
        val px = cx + sx * radius
        val py = cy - ty * radius
        val depth = tz.coerceIn(0f, 1f)
        val alpha = 0.55f + 0.45f * depth
        // Pulse the halo just a touch so the dots feel alive without being noisy.
        val haloR = 6.5f + pulse * 1.8f
        drawCircle(color = accent.copy(alpha = 0.18f * alpha), radius = haloR, center = Offset(px, py))
        drawCircle(color = accent.copy(alpha = 0.30f * alpha), radius = haloR * 0.62f, center = Offset(px, py))
        drawCircle(color = accent.copy(alpha = 0.95f * alpha), radius = 3.2f, center = Offset(px, py))
        drawCircle(color = Color.White.copy(alpha = 0.85f * alpha), radius = 1.3f, center = Offset(px, py))
    }

    // Connection: great-circle arc on the sphere (slerp + project), then pins.
    if (selectedCoord != null) {
        val arcColor = if (isConnected) connectedColor else accent
        drawGreatCircleArc(
            arcPath = arcPath,
            cx = cx, cy = cy, radius = radius,
            cosLat = cosLat, sinLat = sinLat, cosLon = cosLon, sinLon = sinLon,
            startLat = userLat, startLon = userLon,
            endLat = selectedCoord.first, endLon = selectedCoord.second,
            progress = arcProgress,
            shimmer = arcShimmer,
            color = arcColor,
        )
        val userPos = project(userLat, userLon)
        val srvPos = project(selectedCoord.first, selectedCoord.second)
        if (userPos.isSpecified) {
            val uColor = if (isConnected) connectedColor else accent
            drawGlobePin(userPos, uColor, pulse, small = true)
        }
        if (srvPos.isSpecified) {
            drawGlobePin(srvPos, accent, pulse)
        }
    } else {
        val userPos = project(userLat, userLon)
        if (userPos.isSpecified) {
            drawGlobePin(userPos, accent.copy(alpha = 0.95f), pulse, small = true)
        }
    }
}

/** Mullvad-style pin: outer translucent halo + filled disc + inner white dot. */
private fun DrawScope.drawGlobePin(
    center: Offset,
    color: Color,
    pulse: Float,
    small: Boolean = false,
) {
    val halo = (if (small) 11f else 17f) + pulse * 5f
    val disc = if (small) 5f else 7f
    val inner = if (small) 2f else 2.8f
    drawCircle(color = color.copy(alpha = 0.18f), radius = halo, center = center)
    drawCircle(color = color.copy(alpha = 0.34f), radius = halo * 0.62f, center = center)
    drawCircle(color = color, radius = disc, center = center)
    drawCircle(color = Color.White, radius = inner, center = center)
}

/**
 * Great-circle arc on the unit sphere via slerp, projected segment-by-segment.
 * Naturally clips to the visible hemisphere — the polyline simply breaks when
 * a segment dips behind the limb. Lift > 1 floats the arc just off the
 * surface so it reads cleanly against land.
 *
 * Left on the trigonometric path deliberately: 64 iterations, only when a
 * server is selected, which is three orders of magnitude cheaper than the land
 * pass and not worth the readability cost of packing.
 */
@Suppress("LongParameterList")
private fun DrawScope.drawGreatCircleArc(
    arcPath: Path,
    cx: Float, cy: Float, radius: Float,
    cosLat: Float, sinLat: Float, cosLon: Float, sinLon: Float,
    startLat: Double, startLon: Double,
    endLat: Double, endLon: Double,
    progress: Float,
    shimmer: Float,
    color: Color,
) {
    if (progress <= 0f) return
    val phi1 = (startLat * PI / 180.0).toFloat()
    val lam1 = (startLon * PI / 180.0).toFloat()
    val phi2 = (endLat * PI / 180.0).toFloat()
    val lam2 = (endLon * PI / 180.0).toFloat()
    val ax = cos(phi1) * sin(lam1)
    val ay = sin(phi1)
    val az = cos(phi1) * cos(lam1)
    val bx = cos(phi2) * sin(lam2)
    val by = sin(phi2)
    val bz = cos(phi2) * cos(lam2)
    val dot = (ax * bx + ay * by + az * bz).coerceIn(-1f, 1f)
    val omega = acos(dot)
    if (omega < 1e-3f) return
    val sinO = sin(omega)
    val segments = 64
    val travel = (segments * progress).toInt().coerceAtLeast(2)

    arcPath.reset()
    var pen = false
    var anyDrawn = false
    var seg = 0
    while (seg <= travel) {
        val t = seg.toFloat() / segments
        val a = sin((1f - t) * omega) / sinO
        val b = sin(t * omega) / sinO
        val lift = 1f + 0.045f * sin((PI.toFloat()) * t)
        val ux = (a * ax + b * bx) * lift
        val uy = (a * ay + b * by) * lift
        val uz = (a * az + b * bz) * lift
        // Apply camera (lon rot then lat tilt) — same formula as project().
        val sx = ux * cosLon - uz * sinLon
        val sz0 = ux * sinLon + uz * cosLon
        val ty = uy * cosLat - sz0 * sinLat
        val tz = uy * sinLat + sz0 * cosLat
        if (tz < 0f) {
            pen = false
        } else {
            val px = cx + sx * radius
            val py = cy - ty * radius
            if (!pen) {
                arcPath.moveTo(px, py)
                pen = true
            } else {
                arcPath.lineTo(px, py)
            }
            anyDrawn = true
        }
        seg++
    }
    if (!anyDrawn) return

    // Layered glow + crisp gradient stroke.
    drawPath(arcPath, color = color.copy(alpha = 0.10f), style = Stroke(width = 12f, cap = StrokeCap.Round))
    drawPath(arcPath, color = color.copy(alpha = 0.22f), style = Stroke(width = 6f, cap = StrokeCap.Round))
    drawPath(arcPath, color = color.copy(alpha = 0.95f), style = Stroke(width = 2.4f, cap = StrokeCap.Round))

    // Travelling shimmer once the arc is fully drawn.
    if (progress >= 0.99f) {
        val t = shimmer.coerceIn(0f, 1f)
        val a = sin((1f - t) * omega) / sinO
        val b = sin(t * omega) / sinO
        val ux = (a * ax + b * bx) * 1.045f
        val uy = (a * ay + b * by) * 1.045f
        val uz = (a * az + b * bz) * 1.045f
        val sx = ux * cosLon - uz * sinLon
        val sz0 = ux * sinLon + uz * cosLon
        val ty = uy * cosLat - sz0 * sinLat
        val tz = uy * sinLat + sz0 * cosLat
        if (tz >= 0f) {
            val px = cx + sx * radius
            val py = cy - ty * radius
            drawCircle(color = color.copy(alpha = 0.45f), radius = 6f, center = Offset(px, py))
            drawCircle(color = Color.White.copy(alpha = 0.9f), radius = 2.6f, center = Offset(px, py))
        }
    }
}
